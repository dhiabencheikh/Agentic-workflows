import sys
from pathlib import Path

REPO_ROOT = next(p for p in [Path.cwd(), *Path.cwd().parents] if (p / "src" / "constants.py").exists())
sys.path.insert(0, str(REPO_ROOT))

# %%
import json
import statistics

import fsspec
import peft
import torch
import transformers
import trl
from accelerate import init_empty_weights
from peft import LoraConfig, get_peft_model
from transformers import AutoConfig, AutoModelForCausalLM, AutoTokenizer
from trl import DataCollatorForCompletionOnlyLM

from src.constants import BASE_MODEL_ID, BASE_MODEL_REVISION, BUCKET_NAME, PROJECT_ROOT_PATH

# Output of the M1 Vertex run model-training-pipeline-20261112142518
M1_ARTIFACTS = (
    f"gs://{BUCKET_NAME}/vertexai-pipeline-root/123905721265/model-training-pipeline-20261112142518/"
    "data-transformation-component_5095698870994731008"
)
CANDIDATE_LIMITS = [1024, 1536, 2048, 2304, 2560, 3072]
RESPONSE_TEMPLATE = "<|assistant|>"
LORA = {
    "r": 8,
    "lora_alpha": 16,
    "lora_dropout": 0.05,
    "bias": "none",
    "task_type": "CAUSAL_LM",
    "target_modules": ["o_proj", "qkv_proj", "gate_up_proj", "down_proj"],
}

report = [
    "# M2 preparation checks",
    "",
    f"Generated by `notebooks/02_prepare_finetuning.py` on the M1 Vertex outputs `{M1_ARTIFACTS}`.",
    f"Libraries: transformers {transformers.__version__}, peft {peft.__version__}, trl {trl.__version__}, "
    f"torch {torch.__version__}. Model `{BASE_MODEL_ID}` at revision `{BASE_MODEL_REVISION[:7]}`.",
    "",
]

# %% [markdown]
# ## 1. Load the cards and render them with the Phi-3 chat template

# %%
splits = {}
for split in ("train", "validation"):
    with fsspec.open(f"{M1_ARTIFACTS}/{split}_dataset", "r", encoding="utf-8") as file:
        splits[split] = [json.loads(line) for line in file]

tokenizer = AutoTokenizer.from_pretrained(BASE_MODEL_ID, revision=BASE_MODEL_REVISION)
report += [
    "## Tokenizer special tokens",
    "",
    f"- pad: `{tokenizer.pad_token}` (id {tokenizer.pad_token_id}), eos: `{tokenizer.eos_token}` "
    f"(id {tokenizer.eos_token_id}), unk: `{tokenizer.unk_token}` (id {tokenizer.unk_token_id})",
    f"- `{RESPONSE_TEMPLATE}` encodes to {tokenizer.encode(RESPONSE_TEMPLATE, add_special_tokens=False)}, "
    f"`<|end|>` to {tokenizer.encode('<|end|>', add_special_tokens=False)}",
    "",
]


def render(card: dict) -> str:
    return tokenizer.apply_chat_template(card["messages"], tokenize=False)


lengths = {s: [len(tokenizer(render(c), add_special_tokens=False)["input_ids"]) for c in cards] for s, cards in splits.items()}

# %% [markdown]
# ## 2. How many cards would each length limit affect?

# %%
report += [
    "## Cards longer than each candidate limit (tokens, full rendered card)",
    "",
    "| Split | Cards | Max | " + " | ".join(f"> {n}" for n in CANDIDATE_LIMITS) + " |",
    "|---|---|---|" + "---|" * len(CANDIDATE_LIMITS),
]
for split, values in lengths.items():
    report.append(
        f"| {split} | {len(values)} | {max(values)} | "
        + " | ".join(str(sum(v > n for v in values)) for n in CANDIDATE_LIMITS)
        + " |"
    )
report += [
    "",
    "TRL 0.12.2 default when `max_seq_length` is not set: `min(tokenizer.model_max_length, 1024)` "
    f"(tokenizer.model_max_length = {tokenizer.model_max_length}).",
    "",
]
print("\n".join(report[-8:]))

# %% [markdown]
# ## 3. Completion-only loss: which tokens are graded?

# %%
collator = DataCollatorForCompletionOnlyLM(response_template=RESPONSE_TEMPLATE, tokenizer=tokenizer)
graded_share, exact_matches, problems = [], 0, []
for card in splits["train"] + splits["validation"]:
    ids = tokenizer(render(card), add_special_tokens=False)["input_ids"]
    labels = collator.torch_call([{"input_ids": ids}])["labels"][0]
    graded = [t for t, lab in zip(ids, labels.tolist()) if lab != -100]
    graded_text = tokenizer.decode(graded)
    graded_share.append(len(graded) / len(ids))
    expected = card["messages"][-1]["content"]
    if graded_text.strip().startswith(expected.strip()) and "<|end|>" in graded_text:
        exact_matches += 1
    elif len(problems) < 3:
        problems.append((card["example_id"], graded_text[:200]))

example = splits["train"][0]
example_ids = tokenizer(render(example), add_special_tokens=False)["input_ids"]
example_labels = collator.torch_call([{"input_ids": example_ids}])["labels"][0].tolist()
example_graded = tokenizer.decode([t for t, lab in zip(example_ids, example_labels) if lab != -100])

total = len(splits["train"]) + len(splits["validation"])
report += [
    "## Completion-only loss check (train + validation cards)",
    "",
    f"- Collator: `DataCollatorForCompletionOnlyLM(response_template=\"{RESPONSE_TEMPLATE}\")`",
    f"- Cards whose graded tokens are exactly the final tutor reply followed by `<|end|>`: "
    f"**{exact_matches} of {total}**",
    f"- Share of tokens graded per card: median {statistics.median(graded_share):.1%}, "
    f"min {min(graded_share):.1%}, max {max(graded_share):.1%}",
    f"- Without masking, 100% of tokens would be graded.",
    "",
    f"Example `{example['example_id']}`: {len(example_ids)} tokens, graded part:",
    "",
    "```",
    example_graded,
    "```",
    "",
]
if problems:
    report += ["Cards that did not match:", ""] + [f"- `{i}`: `{t!r}`" for i, t in problems] + [""]
print("\n".join(report[-14:]))

# %% [markdown]
# ## 4. LoRA: trainable parameters, without downloading the weights
#
# `init_empty_weights` builds the model skeleton with no memory for the weights,
# which is enough to count parameters and check the LoRA target modules.

# %%
config = AutoConfig.from_pretrained(BASE_MODEL_ID, revision=BASE_MODEL_REVISION)
with init_empty_weights():
    skeleton = AutoModelForCausalLM.from_config(config)
module_names = {name.rsplit(".", 1)[-1] for name, _ in skeleton.named_modules()}
missing = [m for m in LORA["target_modules"] if m not in module_names]
lora_model = get_peft_model(skeleton, LoraConfig(**LORA))
trainable = sum(p.numel() for p in lora_model.parameters() if p.requires_grad)
total_params = sum(p.numel() for p in lora_model.parameters())
layer0 = lora_model.base_model.model.model.layers[0]
qkv = layer0.self_attn.qkv_proj

report += [
    "## LoRA configuration",
    "",
    f"`LoraConfig({', '.join(f'{k}={v!r}' for k, v in LORA.items())})`",
    "",
    f"- Target modules missing from Phi-3: {missing or 'none'}",
    f"- Decoder layers: {config.num_hidden_layers}, hidden size: {config.hidden_size}",
    f"- Trainable parameters: **{trainable:,}** of {total_params:,} (**{trainable / total_params:.2%}**)",
    f"- Example, layer 0 `qkv_proj`: base weight {tuple(qkv.base_layer.weight.shape)}, "
    f"lora_A {tuple(qkv.lora_A['default'].weight.shape)}, lora_B {tuple(qkv.lora_B['default'].weight.shape)}, "
    f"scaling alpha/r = {qkv.scaling['default']}",
    "",
]
print("\n".join(report[-9:]))

# %%
results_path = PROJECT_ROOT_PATH / "docs" / "results" / "m2_finetuning_prep.md"
results_path.write_text("\n".join(report))
print("Written to", results_path)
