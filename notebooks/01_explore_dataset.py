import sys
from pathlib import Path

# Make `src` importable whether this runs from the repo root or from notebooks/.
REPO_ROOT = next(p for p in [Path.cwd(), *Path.cwd().parents] if (p / "src" / "constants.py").exists())
sys.path.insert(0, str(REPO_ROOT))

# %%
import json
import statistics
import tempfile
from collections import Counter
from pathlib import Path

import fsspec
from transformers import AutoTokenizer

from src.constants import NUM_VALIDATION_PROBLEMS, PROJECT_ROOT_PATH, RAW_DATASET_URI, SPLIT_SEED
from src.pipeline_components.data_transformation_component import data_transformation_component
from src.prompts.tutor_system_prompt import TUTOR_SYSTEM_PROMPT, TUTOR_SYSTEM_PROMPT_VERSION

RAW_URI = RAW_DATASET_URI  # same values as the Vertex pipeline run
SEED = SPLIT_SEED
MODEL_ID = "microsoft/Phi-3-mini-4k-instruct"
CONTEXT_WINDOW = 4096
YODA_CSV = Path.home() / "Desktop/Albert School - M2 - S1/Agentic workflows/Practice/yoda_sentences.csv"

report = [
    "# M1 dataset statistics",
    "",
    f"Generated by `notebooks/01_explore_dataset.py` from `{RAW_URI}`.",
    f"Seed {SEED}, {NUM_VALIDATION_PROBLEMS} validation problems, "
    f"system prompt v{TUTOR_SYSTEM_PROMPT_VERSION}, tokenizer `{MODEL_ID}`.",
    "",
]

# %% [markdown]
# ## 1. Raw files: what the authors give us

# %%
fs, root = fsspec.core.url_to_fs(RAW_URI)
raw_rows = []
for folder in ("train", "testset"):
    for path in sorted(fs.glob(f"{root}/{folder}/*.txt")):
        name = path.rsplit("/", 1)[-1]
        text = fs.cat(path).decode("utf-8")
        dialogue = text.split("<dialogue>", 1)[-1]
        raw_rows.append(
            {
                "folder": folder,
                "type": "socratic_dialogue" if name.endswith("_socratic_dialogue.txt") else "thread",
                "problem": name.split("_")[0],
                "tutor_turns": sum(1 for line in dialogue.split("\n") if line.startswith("Assistant:")),
            }
        )

report += ["## Raw files", "", "| Folder | Type | Files | Problems | Tutor turns |", "|---|---|---|---|---|"]
for folder in ("train", "testset"):
    for kind in ("socratic_dialogue", "thread"):
        rows = [r for r in raw_rows if r["folder"] == folder and r["type"] == kind]
        report.append(
            f"| {folder} | {kind} | {len(rows)} | {len({r['problem'] for r in rows})} "
            f"| {sum(r['tutor_turns'] for r in rows)} |"
        )
report.append("")
print("\n".join(report))

# %% [markdown]
# ## 2. Run the component locally (same code as on Vertex)

# %%
out_dir = Path(tempfile.mkdtemp())
outputs = {split: out_dir / f"{split}.jsonl" for split in ("train", "validation", "test")}
data_transformation_component.python_func(
    raw_dataset_uri=RAW_URI,
    system_prompt=TUTOR_SYSTEM_PROMPT,
    num_validation_problems=NUM_VALIDATION_PROBLEMS,
    seed=SEED,
    train_dataset=str(outputs["train"]),
    validation_dataset=str(outputs["validation"]),
    test_dataset=str(outputs["test"]),
)
splits = {s: [json.loads(line) for line in p.read_text().splitlines()] for s, p in outputs.items()}

# %%
report += [
    "## Examples after formatting and deduplication",
    "",
    "| Split | Examples | Problems | Problem ids | From dialogues | From threads |",
    "|---|---|---|---|---|---|",
]
for split, examples in splits.items():
    ids = sorted({e["problem_id"] for e in examples}, key=int)
    kinds = Counter(e["file_type"] for e in examples)
    report.append(
        f"| {split} | {len(examples)} | {len(ids)} | {', '.join(ids)} "
        f"| {kinds['socratic_dialogue']} | {kinds['conversational_thread']} |"
    )
alts = [len(e["reference_alternatives"]) for e in splits["test"]]
report += [
    "",
    f"Test examples with at least one alternative reference reply: "
    f"{sum(a > 0 for a in alts)} of {len(alts)} (max {max(alts)} alternatives).",
    "",
]
print("\n".join(report[-12:]))

# %% [markdown]
# ## 3. Token lengths with the Phi-3 tokenizer (4k context window)
#
# Length = the whole example after the Phi-3 chat template, as the model will see it in training.

# %%
tokenizer = AutoTokenizer.from_pretrained(MODEL_ID)


def n_tokens(messages: list) -> int:
    return len(tokenizer.apply_chat_template(messages, tokenize=True))


def percentile(values: list, q: float) -> int:
    ordered = sorted(values)
    return ordered[min(len(ordered) - 1, int(q * len(ordered)))]


report += [
    "## Token lengths (full example, Phi-3 chat template)",
    "",
    f"| Split | Min | Median | 95th percentile | Max | Over {CONTEXT_WINDOW} | Target reply median | Target reply max |",
    "|---|---|---|---|---|---|---|---|",
]
for split, examples in splits.items():
    lengths = [n_tokens(e["messages"]) for e in examples]
    targets = [len(tokenizer(e["messages"][-1]["content"])["input_ids"]) for e in examples]
    report.append(
        f"| {split} | {min(lengths)} | {int(statistics.median(lengths))} | {percentile(lengths, 0.95)} "
        f"| {max(lengths)} | {sum(n > CONTEXT_WINDOW for n in lengths)} "
        f"| {int(statistics.median(targets))} | {max(targets)} |"
    )
report.append("")
print("\n".join(report[-8:]))

# %% [markdown]
# ## 4. Does the Phi-3 chat template keep the system message?

# %%
probe = [
    {"role": "system", "content": "SYSTEM_PROBE"},
    {"role": "user", "content": "USER_PROBE"},
    {"role": "assistant", "content": "ASSISTANT_PROBE"},
]
rendered = tokenizer.apply_chat_template(probe, tokenize=False)
report += [
    "## Phi-3 chat template and the system message",
    "",
    f"System text kept by the template: **{'SYSTEM_PROBE' in rendered}**",
    "",
    "Rendered probe:",
    "",
    "```",
    rendered,
    "```",
    "",
]
print(rendered)

