# %% [markdown]
# # M3: calibrating the best-match ROUGE-L metric
#
# 1. Implementation check: our plain-Python ROUGE-L F1 against the reference
#    `rouge-score` library, on train + validation human replies.
# 2. Human ceiling: how human tutors' alternative replies score against the other
#    references on the 80 test cases, to know what a model score means.
#
# Run (rouge-score is loaded for this run only, not added to the project):
# `uv run --with rouge-score python notebooks/03_similarity_calibration.py`
# Figures are written to `docs/results/m3_similarity_calibration.md`.

# %%
import sys
from pathlib import Path

REPO_ROOT = next(p for p in [Path.cwd(), *Path.cwd().parents] if (p / "src" / "constants.py").exists())
sys.path.insert(0, str(REPO_ROOT))

# %%
import json
import statistics

import fsspec
from rouge_score import rouge_scorer

from eval.similarity import best_match_rouge_l, rouge_l
from src.constants import BUCKET_NAME, PROJECT_ROOT_PATH

M1_ARTIFACTS = (
    f"gs://{BUCKET_NAME}/vertexai-pipeline-root/123905721265/model-training-pipeline-20261112142518/"
    "data-transformation-component_5095698870994731008"
)
splits = {}
for split in ("train", "validation", "test"):
    with fsspec.open(f"{M1_ARTIFACTS}/{split}_dataset", "r", encoding="utf-8") as file:
        splits[split] = [json.loads(line) for line in file]

report = [
    "# M3 similarity calibration (best-match ROUGE-L F1)",
    "",
    f"Generated by `notebooks/03_similarity_calibration.py` on the M1 Vertex outputs `{M1_ARTIFACTS}`.",
    "",
]

# %% [markdown]
# ## 1. Our implementation against rouge-score (train + validation)

# %%
scorer = rouge_scorer.RougeScorer(["rougeL"], use_stemmer=False)
pairs = [
    (alt, card["messages"][-1]["content"])
    for card in splits["train"] + splits["validation"]
    for alt in card["reference_alternatives"]
]
differences = [abs(rouge_l(a, r)["f1"] - scorer.score(r, a)["rougeL"].fmeasure) for a, r in pairs]
report += [
    "## Implementation check against `rouge-score` (rougeL, no stemming)",
    "",
    f"- Pairs compared (alternative vs reference, train + validation): {len(pairs)}",
    f"- Largest absolute difference in F1: {max(differences):.2e}",
    f"- Pairs with a difference above 1e-9: {sum(d > 1e-9 for d in differences)}",
    "",
]
print("\n".join(report[-5:]))

# %% [markdown]
# ## 2. Human ceiling on the 80 test cases
#
# For each test case with alternatives, each human alternative is scored with
# best-match against the reference and the OTHER alternatives (never itself).

# %%
per_reply = []
cards_with_alts = [c for c in splits["test"] if c["reference_alternatives"]]
for card in cards_with_alts:
    reference = card["messages"][-1]["content"]
    alts = card["reference_alternatives"]
    for i, alt in enumerate(alts):
        others = alts[:i] + alts[i + 1 :]
        per_reply.append(best_match_rouge_l(alt, reference, others)["f1"])
# Reference reply scored against its alternatives only
reference_vs_alts = [
    best_match_rouge_l(c["messages"][-1]["content"], c["reference_alternatives"][0], c["reference_alternatives"][1:])["f1"]
    for c in cards_with_alts
]


def describe(values: list) -> str:
    ordered = sorted(values)
    q = lambda f: ordered[min(len(ordered) - 1, int(f * len(ordered)))]
    return (
        f"n={len(values)}, mean {statistics.mean(values):.3f}, median {statistics.median(values):.3f}, "
        f"25th percentile {q(0.25):.3f}, 75th percentile {q(0.75):.3f}, min {min(values):.3f}, max {max(values):.3f}"
    )


report += [
    "## Human ceiling on the test cases",
    "",
    f"- Test cases with at least one alternative: {len(cards_with_alts)} of {len(splits['test'])}",
    f"- Each human alternative vs the reference and the other alternatives: {describe(per_reply)}",
    f"- Each reference vs its alternatives: {describe(reference_vs_alts)}",
    "",
    "Reading: a human tutor's valid reply typically reaches these scores against the other human replies.",
    "A model scoring in the same range writes replies as close to the references as another human tutor would;",
    "a much lower score means different wording, which is not necessarily worse (see the LLM judge in M3).",
    "",
]
print("\n".join(report[-9:]))

# %%
results_path = PROJECT_ROOT_PATH / "docs" / "results" / "m3_similarity_calibration.md"
results_path.write_text("\n".join(report))
print("Written to", results_path)
