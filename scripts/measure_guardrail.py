"""Measure the input guardrail without GPU: block rate on adversarial inputs, false-block rate on real students.

Inputs checked: the student's latest message of each case.
- adversarial: the 26 hand-written cases (eval/triples_adversarial.jsonl), by category
- normal: the 80 test cards (eval/test_cards.jsonl) and, for a larger false-block sample, every
  student turn of the train and validation cards (M1 outputs)
Writes docs/results/m6_guardrail.md.  Run: uv run --no-dev python -m scripts.measure_guardrail
"""

import json
from collections import defaultdict
from pathlib import Path

import fsspec

from src.constants import BUCKET_NAME
from src.eval_cases import card_to_case
from src.guardrail import check_input

ROOT = Path(__file__).resolve().parents[1]
M1 = (f"gs://{BUCKET_NAME}/vertexai-pipeline-root/123905721265/model-training-pipeline-20261112142518/"
      "data-transformation-component_5095698870994731008")


def load_jsonl(path) -> list:
    with fsspec.open(str(path), "r", encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


def main() -> None:
    adversarial = load_jsonl(ROOT / "eval" / "triples_adversarial.jsonl")
    test = [card_to_case(c) for c in load_jsonl(ROOT / "eval" / "test_cards.jsonl")]
    by_cat = defaultdict(lambda: [0, 0])
    for case in adversarial:
        hit = check_input(case["messages"][-1]["content"])["blocked"]
        by_cat[case["category"]][0] += hit
        by_cat[case["category"]][1] += 1
    test_blocked = [c["id"] for c in test if check_input(c["messages"][-1]["content"])["blocked"]]
    student_turns, blocked_examples = 0, []
    for split in ("train", "validation"):
        seen = set()
        for card in load_jsonl(f"{M1}/{split}_dataset"):
            for m in card["messages"]:
                if m["role"] == "user" and m["content"] not in seen:
                    seen.add(m["content"])
                    student_turns += 1
                    result = check_input(m["content"])
                    if result["blocked"]:
                        blocked_examples.append((card["example_id"], result["family"], m["content"][-160:]))
    lines = [
        "# M6 input guardrail: prompt-injection check (no GPU)",
        "",
        "Generated by `scripts/measure_guardrail.py`; guardrail `src/guardrail.py`. Input checked: the student's latest message.",
        "",
        "| Inputs | Blocked | Should be |",
        "|---|---|---|",
    ]
    for cat in ("prompt_injection", "ask_for_answer", "off_topic"):
        k, n = by_cat[cat]
        lines.append(f"| adversarial: {cat} | {k}/{n} | {'blocked' if cat == 'prompt_injection' else 'not blocked (handled by the model)'} |")
    lines += [
        f"| 80 test cards (normal students) | {len(test_blocked)}/80 | not blocked |",
        f"| train + validation student turns (distinct) | {len(blocked_examples)}/{student_turns} | not blocked |",
        "",
        "Caveat: the 10 prompt-injection cases were read before the patterns were written, so their block rate is "
        "optimistic; the false-block rate on real student messages is the more reliable figure.",
        "",
    ]
    if test_blocked or blocked_examples:
        lines += ["False blocks:", ""] + [f"- `{i}`" for i in test_blocked] + [f"- `{i}` ({f}): {t!r}" for i, f, t in blocked_examples[:10]] + [""]
    out = ROOT / "docs" / "results" / "m6_guardrail.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
