"""Measure the output guardrail without GPU, as the live app would run it (student's code, no answer key).

- model replies: the 212 recorded M3 predictions (setups b and c), against the full leak check's verdict
- human tutor replies (should never be blocked): test (reference + alternatives) and train + validation
Writes docs/results/m6_output_guardrail.md.  Run: uv run --no-dev python -m scripts.measure_output_guardrail
"""

import csv
import json
from pathlib import Path

import fsspec

from src.constants import BUCKET_NAME
from src.eval_cases import card_to_case
from src.output_guardrail import check_reply

ROOT = Path(__file__).resolve().parents[1]
M1 = (f"gs://{BUCKET_NAME}/vertexai-pipeline-root/123905721265/model-training-pipeline-20261112142518/"
      "data-transformation-component_5095698870994731008")


def load_jsonl(path) -> list:
    with fsspec.open(str(path), "r", encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


def main() -> None:
    cases = {c["id"]: c for c in (card_to_case(x) for x in load_jsonl(ROOT / "eval/test_cards.jsonl"))}
    cases.update({c["id"]: c for c in load_jsonl(ROOT / "eval/triples_adversarial.jsonl")})
    rows = list(csv.DictReader(open(ROOT / "docs/results/m3_eval_cases.csv", encoding="utf-8")))
    lines = ["# M6 output guardrail: leak check on the reply before it is shown (no GPU)", "",
             "Generated by `scripts/measure_output_guardrail.py`; guardrail `src/output_guardrail.py` "
             "(student's code from the first message, no answer key).", "",
             "| Model replies | Blocked | Of which flagged by the full M3 leak check | Full-check leaks not blocked |",
             "|---|---|---|---|"]
    for setup in ("b", "c"):
        mine = [r for r in rows if r["setup"] == setup]
        blocked = [r for r in mine if check_reply(r["response"] or "", cases[r["case_id"]]["messages"])["blocked"]]
        full = {r["case_id"] for r in mine if r["status"] == "leak"}
        caught = {r["case_id"] for r in blocked} & full
        lines.append(f"| setup {setup} ({len(mine)}) | {len(blocked)} | {len(caught)} | {len(full - caught)}: {sorted(full - caught)} |")
        extra = sorted({r['case_id'] for r in blocked} - full)
        if extra:
            lines.append(f"|  | blocked but not flagged by the full check: {extra} | | |")
    human_test = [(c["messages"], r) for c in cases.values() if c.get("source") == "test_split"
                  for r in [c["reference"], *c["reference_alternatives"]]]
    blocked_test = sum(check_reply(r, m)["blocked"] for m, r in human_test)
    human_tv, examples = 0, []
    for split in ("train", "validation"):
        for card in load_jsonl(f"{M1}/{split}_dataset"):
            case = card_to_case(card)
            for r in [case["reference"], *case["reference_alternatives"]]:
                human_tv += 1
                res = check_reply(r, case["messages"])
                if res["blocked"]:
                    examples.append((card["example_id"], res["leak_type"], r[:120]))
    lines += ["", "| Human tutor replies (should never be blocked) | Blocked |", "|---|---|",
              f"| test: reference + alternatives | {blocked_test}/{len(human_test)} |",
              f"| train + validation: reference + alternatives | {len(examples)}/{human_tv} |", ""]
    if examples:
        lines += ["Human replies blocked:", ""] + [f"- `{i}` ({t}): {r!r}" for i, t, r in examples[:10]] + [""]
    (ROOT / "docs/results/m6_output_guardrail.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
